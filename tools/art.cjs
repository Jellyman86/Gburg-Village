#!/usr/bin/env node
// Art manifest tool for the living version.
//   node tools/art.cjs build   update hashes/dimensions in v8/data/art.json and regenerate v8/src/art.js
//   node tools/art.cjs check   fail if any file is missing, stale, unmanaged or art.js is out of date
// Entries: "id": { "file": "characters/jason.png", "hash": "...", "width": 256, "height": 512, "source"?: "Inbox name.png", "sourceHash"?: "..." }
// IDs follow <category>.<name>[.<variant>] and are referenced in code through V8_ART.url('id').
'use strict';
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');

const root=path.resolve(__dirname,'..'),live=path.join(root,'v8');
const manifestPath=path.join(live,'data','art.json');
const generatedPath=path.join(live,'src','art.js');
const assetRoot=path.join(live,'assets');
const IMAGE=/\.(png|webp)$/i;

const sha256=buffer=>crypto.createHash('sha256').update(buffer).digest('hex');

function dimensions(buffer,file){
 if(buffer.length>24&&buffer.toString('ascii',1,4)==='PNG')return {width:buffer.readUInt32BE(16),height:buffer.readUInt32BE(20)};
 if(buffer.length>30&&buffer.toString('ascii',0,4)==='RIFF'&&buffer.toString('ascii',8,12)==='WEBP'){
  const chunk=buffer.toString('ascii',12,16);
  if(chunk==='VP8 ')return {width:buffer.readUInt16LE(26)&0x3fff,height:buffer.readUInt16LE(28)&0x3fff};
  if(chunk==='VP8L'){const bits=buffer.readUInt32LE(21);return {width:(bits&0x3fff)+1,height:((bits>>14)&0x3fff)+1};}
  if(chunk==='VP8X')return {width:1+buffer.readUIntLE(24,3),height:1+buffer.readUIntLE(27,3)};
 }
 throw new Error('Unsupported image format: '+file);
}

function readManifest(){
 const data=JSON.parse(fs.readFileSync(manifestPath,'utf8'));
 if(data.version!==1||typeof data.assets!=='object')throw new Error('art.json must have version 1 and an assets object');
 return data;
}

// Add or update one entry (file/source/sourceHash) in art.json; hashes and sizes are filled by build().
function upsert(id,fields){
 const data=readManifest();
 const current=data.assets[id]||{};
 const entry={file:fields.file||current.file};
 if(!entry.file)throw new Error('Entry needs a file: '+id);
 if(fields.source!==undefined)entry.source=fields.source;else if(current.source!==undefined)entry.source=current.source;
 if(fields.sourceHash!==undefined)entry.sourceHash=fields.sourceHash;else if(current.sourceHash!==undefined)entry.sourceHash=current.sourceHash;
 data.assets[id]=entry;
 fs.writeFileSync(manifestPath,JSON.stringify(data,null,1)+'\n');
 return build({quiet:true});
}

function listAssetFiles(){
 const out=[];
 (function walk(dir){
  for(const entry of fs.readdirSync(dir,{withFileTypes:true})){
   const full=path.join(dir,entry.name);
   if(entry.isDirectory())walk(full);else if(IMAGE.test(entry.name))out.push(path.relative(assetRoot,full).split(path.sep).join('/'));
  }
 })(assetRoot);
 return out.sort();
}

// Resolve every entry against the files on disk. Returns the updated manifest plus a list of differences.
function resolve(data){
 const next={version:1,root:'assets/',assets:{}},changes=[],files=new Set(listAssetFiles());
 for(const id of Object.keys(data.assets).sort()){
  const entry=data.assets[id];
  if(!/^[a-z0-9]+(\.[a-z0-9-]+)+$/.test(id))throw new Error('Invalid art id (use category.name[.variant]): '+id);
  if(typeof entry.file!=='string'||!IMAGE.test(entry.file))throw new Error('Entry needs a .png/.webp file: '+id);
  const full=path.join(assetRoot,entry.file);
  if(!fs.existsSync(full))throw new Error('Missing asset file for '+id+': v8/assets/'+entry.file);
  const buffer=fs.readFileSync(full),hash=sha256(buffer),{width,height}=dimensions(buffer,entry.file);
  const resolved={file:entry.file,hash,width,height};
  if(entry.source!==undefined)resolved.source=entry.source;
  if(entry.sourceHash!==undefined)resolved.sourceHash=entry.sourceHash;
  if(entry.hash!==hash)changes.push(id+': hash '+(entry.hash?entry.hash.slice(0,10)+' → ':'set ')+hash.slice(0,10));
  if(entry.width!==width||entry.height!==height)changes.push(id+': size '+(entry.width?entry.width+'x'+entry.height+' → ':'set ')+width+'x'+height);
  next.assets[id]=resolved;
  files.delete(entry.file);
 }
 const unmanaged=[...files];
 return {next,changes,unmanaged};
}

function generate(data){
 const lines=[
  '// GENERATED by tools/art.cjs from v8/data/art.json - edit the JSON and run `npm run art:build`.',
  '// V8_ART.url(id) returns a cache-busted relative URL for an art id.',
  '((root)=>{',
  " 'use strict';",
  ' const data='+JSON.stringify(data)+';',
  ' const entry=id=>{const a=data.assets[id];if(!a)throw new Error("Unknown art id: "+id);return a;};',
  " const url=id=>data.root+entry(id).file+'?v='+entry(id).hash.slice(0,10);",
  ' const api=Object.freeze({url,entry,has:id=>Object.hasOwn(data.assets,id),ids:()=>Object.keys(data.assets),root:data.root});',
  ' root.V8_ART=api;if(root!==globalThis)globalThis.V8_ART=api;',
  " if(typeof module!=='undefined'&&module.exports)module.exports=api;",
  "})(typeof window==='undefined'?globalThis:window);",
  ''
 ];
 return lines.join('\n');
}

function analyze(){
 const data=readManifest();
 const {next,changes,unmanaged}=resolve(data);
 const serialized=JSON.stringify(next,null,1)+'\n',generated=generate(next);
 const same=(file,text)=>fs.existsSync(file)&&fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n')===text;
 return {next,changes,unmanaged,serialized,generated,
  manifestStale:!same(manifestPath,serialized),
  generatedStale:!same(generatedPath,generated)};
}

function build({quiet=false}={}){
 const a=analyze(),count=Object.keys(a.next.assets).length;
 if(a.manifestStale)fs.writeFileSync(manifestPath,a.serialized);
 if(a.generatedStale)fs.writeFileSync(generatedPath,a.generated);
 if(!quiet){
  for(const line of a.changes)console.log('  '+line);
  console.log(`✔ art.json: ${count} assets${a.changes.length?`, ${a.changes.length} updated`:''}; src/art.js ${a.generatedStale?'regenerated':'unchanged'}.`);
 }
 if(a.unmanaged.length)console.warn('⚠ Files in v8/assets without a manifest entry:\n  '+a.unmanaged.join('\n  '));
 return a;
}

function check(){
 const a=analyze(),count=Object.keys(a.next.assets).length,problems=[];
 if(a.changes.length)problems.push('Stale manifest fields:\n  '+a.changes.join('\n  '));
 if(a.manifestStale&&!a.changes.length)problems.push('art.json formatting differs from tools/art.cjs output (run `npm run art:build`).');
 if(a.generatedStale)problems.push('v8/src/art.js is out of date (run `npm run art:build`).');
 if(a.unmanaged.length)problems.push('Files in v8/assets without a manifest entry:\n  '+a.unmanaged.join('\n  '));
 if(problems.length){console.error('✖ Art manifest check failed.\n'+problems.join('\n'));return false;}
 console.log(`✔ Art manifest: ${count} assets present with matching hashes and dimensions; src/art.js is current.`);
 return true;
}

module.exports={readManifest,upsert,build,check,dimensions,sha256,manifestPath,assetRoot,live,root};

if(require.main===module){
 const command=process.argv[2];
 if(command==='build')build();
 else if(command==='check'){if(!check())process.exit(1);}
 else{console.error('Usage: node tools/art.cjs build|check');process.exit(2);}
}
